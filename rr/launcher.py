"""Launch queued runs onto free GPUs, track them, collect results, cancel them.

Each run gets `runs/<study>/<run_id>/` holding a git worktree of its exact
commit (`code/`), a generated `run.sh`, and the files the run writes:
log.txt, heartbeat.json, final_metrics.json, started_at, exit_code. The run
lives in its own detached tmux session on its node, so it outlives rr.

This assumes the nodes share the run directory's filesystem with the
controller (`rr doctor` checks it): rr writes run.sh and reads exit_code
locally.
"""

from __future__ import annotations

import os
import shlex
import time
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Callable, Iterable, Optional

from . import approval as approvalmod
from . import gitutil
from . import gpus as gpumod
from .config import Config
from .ledger import HOLDS_GPUS, Ledger, reserved_gpus
from .metrics import MetricError, hash_paths, read_metric
from .nodes import NodeError, NodeRunner
from .project import Project, all_ledgers, register_ledger
from .queue import budget_allows, session_name
from .spec import Metric, SpecError, load_spec
from .statefile import file_lock

# A run left in `launching` with no tmux session after this long never started.
LAUNCH_GRACE_S = 120
LOG_TAIL_CHARS = 300

RUN_SH = """#!/usr/bin/env bash
# Generated by rr for {study}/{run_id}. Do not edit: rr reads the files this writes.
set -u
RUN_DIR={run_dir}
exec >>"$RUN_DIR/log.txt" 2>&1
finish() {{ echo "$1" >"$RUN_DIR/exit_code.tmp" && mv "$RUN_DIR/exit_code.tmp" "$RUN_DIR/exit_code"; }}
cd {code_dir} || {{ echo "[rr] cannot cd to code dir"; finish 127; exit 127; }}

# nvidia-smi numbers GPUs by PCI bus; make CUDA use the same numbering.
export CUDA_DEVICE_ORDER=PCI_BUS_ID
export CUDA_VISIBLE_DEVICES={cuda}
export RR_STUDY={study_q} RR_RUN_ID={run_id_q} RR_ARM={arm} RR_SEED={seed} RR_KIND={kind}
export RR_RUN_DIR="$RUN_DIR" RR_HEARTBEAT="$RUN_DIR/heartbeat.json" RR_FINAL_METRICS="$RUN_DIR/final_metrics.json"
export WANDB_RUN_GROUP={study_q} WANDB_NAME={run_id_q} WANDB_JOB_TYPE={kind} WANDB_TAGS={tags}

echo "[rr] $(date -u +%Y-%m-%dT%H:%M:%SZ) start {run_id} on $(hostname) gpus=$CUDA_VISIBLE_DEVICES commit={git_sha}"
date +%s >"$RUN_DIR/started_at"

# Job control puts the command and the watchdog in their own process groups,
# so stopping a run stops every process it started (dataloader workers too).
set -m
bash -c {command} </dev/null &
child=$!
( sleep {timeout_s}; echo "[rr] timeout after {timeout_s}s"; touch "$RUN_DIR/timed_out"
  kill -TERM -- "-$child"; sleep 60; kill -KILL -- "-$child" ) </dev/null &
watchdog=$!
set +m
echo "$child" >"$RUN_DIR/pid"

stop() {{
  echo "[rr] stop requested"
  kill -TERM -- "-$child" 2>/dev/null
  ( sleep 30; kill -KILL -- "-$child" 2>/dev/null ) &
}}
trap stop HUP INT TERM

wait "$child"; rc=$?
# A trapped signal interrupts `wait`; keep waiting for the real exit status.
while kill -0 "$child" 2>/dev/null; do wait "$child"; rc=$?; done
kill -- "-$watchdog" 2>/dev/null
[ -e "$RUN_DIR/timed_out" ] && rc=124
echo "[rr] $(date -u +%Y-%m-%dT%H:%M:%SZ) exit $rc"
finish "$rc"
"""


@dataclass
class Outcome:
    study: str
    run_id: str
    action: str  # launched | waiting | skipped | crashed | requeued | running | done | invalid | lost
    detail: str = ""

    def __str__(self) -> str:
        return f"{self.study}/{self.run_id}: {self.action}{' - ' + self.detail if self.detail else ''}"


def render_run_sh(rec: dict, gpus: list) -> str:
    q = shlex.quote
    run_dir = Path(rec["run_dir"])
    tags = f"arm:{rec['arm']},seed:{rec['seed']},kind:{rec['kind']}"
    return RUN_SH.format(
        study=rec["study"],
        run_id=rec["run_id"],
        study_q=q(rec["study"]),
        run_id_q=q(rec["run_id"]),
        run_dir=q(str(run_dir)),
        code_dir=q(str(run_dir / "code")),
        cuda=",".join(str(g) for g in gpus),
        arm=q(rec["arm"]),
        seed=int(rec["seed"]),
        kind=q(rec["kind"]),
        tags=q(tags),
        git_sha=rec["git_sha"][:12],
        command=q(rec["command"]),
        timeout_s=int(rec["timeout_s"]),
    )


def prepare_run_dir(project: Project, rec: dict, gpus: list) -> Path:
    """Create the run dir, its worktree at the exact commit, and run.sh."""
    run_dir = Path(rec["run_dir"])
    run_dir.mkdir(parents=True, exist_ok=True)
    code = run_dir / "code"
    if code.exists():
        head = gitutil.head_of(code)
        if head != rec["git_sha"]:
            raise gitutil.GitError(f"{code} is at {head[:12]}, expected {rec['git_sha'][:12]}")
    else:
        gitutil.worktree_add(project.root, code, rec["git_sha"])
    for stale in ("exit_code", "timed_out", "pid", "started_at"):
        (run_dir / stale).unlink(missing_ok=True)
    script = run_dir / "run.sh"
    script.write_text(render_run_sh(rec, gpus))
    script.chmod(0o755)
    return run_dir


def blocked_reason(config: Config, project: Project) -> Optional[str]:
    for path in (project.root / "PAUSE", config.state_dir / "PAUSE"):
        if path.exists():
            return f"paused ({path} exists)"
    if (config.state_dir / "DRAIN").exists():
        return "draining (rr drain --off to resume)"
    return None


def _log_tail(run_dir: Path) -> str:
    try:
        with open(run_dir / "log.txt", "rb") as fh:
            fh.seek(0, os.SEEK_END)
            fh.seek(max(0, fh.tell() - 4096))
            lines = [l for l in fh.read().decode(errors="replace").splitlines() if l.strip() and not l.startswith("[rr]")]
    except FileNotFoundError:
        return ""
    return lines[-1][-LOG_TAIL_CHARS:] if lines else ""


def _read_float(path: Path) -> Optional[float]:
    try:
        return float(path.read_text().strip())
    except (FileNotFoundError, ValueError):
        return None


class Launcher:
    def __init__(
        self,
        config: Config,
        project: Project,
        runner: Optional[NodeRunner] = None,
        clock: Callable[[], float] = time.time,
        wall_clock: Optional[Callable[[], datetime]] = None,
    ):
        self.config = config
        self.project = project
        self.clock = clock
        self.wall_clock = wall_clock or (lambda: datetime.fromtimestamp(self.clock()))
        self.runner = runner or NodeRunner(config, clock=clock)
        self.gpu_state = gpumod.GpuState(config, clock=clock)
        self.hash_cache = config.state_dir / "hashcache.json"
        self.lock_path = config.state_dir / "launch"

    def _studies(self, studies: Optional[Iterable[str]]) -> list:
        return list(studies) if studies else self.project.study_ids()

    def ledger(self, study: str) -> Ledger:
        lg = Ledger(self.project.study_dir(study) / "ledger.jsonl", clock=self.clock)
        register_ledger(self.config, lg)
        return lg

    # ------------------------------------------------------------ one scheduling pass

    def tick(self, studies: Optional[Iterable[str]] = None) -> list:
        """Reconcile running runs, then launch what fits. Safe to call repeatedly."""
        with file_lock(self.lock_path):
            out = self._reconcile(self._studies(studies))
            out += self._launch_pending(self._studies(studies))
        return out

    def reconcile(self, studies: Optional[Iterable[str]] = None) -> list:
        with file_lock(self.lock_path):
            return self._reconcile(self._studies(studies))

    # ------------------------------------------------------------ launching

    def _launch_pending(self, studies: list) -> list:
        why = blocked_reason(self.config, self.project)
        if why:
            return [Outcome("*", "*", "skipped", why)]
        state = self.gpu_state.refresh(self.runner)
        reserved = reserved_gpus(all_ledgers(self.config, self.project))
        out = []
        for study in studies:
            try:
                spec = load_spec(self.project.study_dir(study) / "spec.yaml")
            except SpecError as e:
                out.append(Outcome(study, "*", "skipped", f"spec error: {e}"))
                continue
            ledger = self.ledger(study)
            runs = ledger.runs()
            queued = [r for r in runs.values() if r["state"] == "queued"]
            if not queued:
                continue
            queued.sort(key=lambda r: (r["kind"] != "smoke", r["created_at"]))
            approval = None
            active = sum(1 for r in runs.values() if r["state"] in HOLDS_GPUS)
            for rec in queued:
                if active >= spec.max_concurrent_runs:
                    out.append(Outcome(study, rec["run_id"], "waiting", f"max_concurrent_runs={spec.max_concurrent_runs}"))
                    continue
                if rec["kind"] != "smoke":
                    if approval is None:
                        approval = approvalmod.check(self.project, spec, self.hash_cache)
                    if not approval.valid:
                        out.append(Outcome(study, rec["run_id"], "waiting", f"approval: {approval.reason}"))
                        continue
                    if rec.get("spec_hash") != approval.approval["approval_hash"]:
                        out.append(Outcome(study, rec["run_id"], "waiting", "queued under a different approval"))
                        continue
                if rec["kind"] == "full" and spec.require_smoke:
                    smoked = any(
                        r["kind"] == "smoke" and r["arm"] == rec["arm"] and r["state"] == "done" and r.get("git_sha") == rec["git_sha"]
                        for r in runs.values()
                    )
                    if not smoked:
                        out.append(Outcome(study, rec["run_id"], "waiting", f"no successful smoke run of {rec['arm']} at {rec['git_sha'][:7]}"))
                        continue
                over = budget_allows(spec, list(runs.values()), rec, self.clock())
                if over:
                    out.append(Outcome(study, rec["run_id"], "waiting", over))
                    continue
                alloc = gpumod.allocate(
                    state, self.config, rec["n_gpus"], reserved, self.clock(), rec.get("gpu_type"), self.wall_clock()
                )
                if alloc is None:
                    out.append(Outcome(study, rec["run_id"], "waiting", f"no {rec['n_gpus']} free GPU(s) within caps"))
                    continue
                o = self._launch_one(ledger, rec, alloc)
                out.append(o)
                if o.action == "launched":
                    active += 1
                    runs = ledger.runs()
                # Whether it launched or the re-probe found the GPUs taken,
                # don't hand the same GPUs to another run in this pass.
                reserved |= {(alloc.node, g) for g in alloc.gpus}
        return out

    def _launch_one(self, ledger: Ledger, rec: dict, alloc: gpumod.Allocation) -> Outcome:
        study, run_id = rec["study"], rec["run_id"]
        try:
            prepare_run_dir(self.project, rec, alloc.gpus)
        except (gitutil.GitError, OSError) as e:
            ledger.transition(run_id, "crash", notes=f"could not prepare run dir: {e}")
            return Outcome(study, run_id, "crashed", f"could not prepare run dir: {e}")

        try:
            probe = gpumod.probe_node(self.runner, alloc.node)
        except (NodeError, gpumod.ProbeError) as e:
            return Outcome(study, run_id, "waiting", f"re-probe of {alloc.node} failed: {e}")
        if not gpumod.still_idle(probe, alloc.gpus, self.config.policy):
            return Outcome(study, run_id, "waiting", f"re-probe: {alloc.node} GPUs {alloc.gpus} no longer idle")

        session = session_name(study, run_id)
        ledger.transition(
            run_id, "launching", node=alloc.node, gpus=alloc.gpus, gpu_type=alloc.gpu_type, tmux_session=session
        )
        run_sh = shlex.quote(str(Path(rec["run_dir"]) / "run.sh"))
        cmd = f"tmux new-session -d -s {shlex.quote(session)} {shlex.quote('bash ' + run_sh)}"
        try:
            res = self.runner.run(alloc.node, cmd)
        except NodeError as e:
            # The session may or may not have started; reconcile decides from
            # what's actually on the node rather than risk a double launch.
            return Outcome(study, run_id, "launching", f"no answer from {alloc.node}; will check: {e}")
        if res.returncode != 0:
            ledger.transition(run_id, "crash", notes=f"tmux new-session failed: {(res.stderr or res.stdout).strip()[-200:]}")
            return Outcome(study, run_id, "crashed", "tmux new-session failed")
        ledger.transition(run_id, "running", started_at=self.clock())
        return Outcome(study, run_id, "launched", f"{alloc.node} GPUs {','.join(map(str, alloc.gpus))}")

    # ------------------------------------------------------------ tracking

    def session_alive(self, node: str, session: str) -> Optional[bool]:
        """True/False, or None if the node couldn't be asked."""
        try:
            res = self.runner.run(node, f"tmux has-session -t {shlex.quote('=' + session)} 2>/dev/null")
        except NodeError:
            return None
        return res.returncode == 0

    def _reconcile(self, studies: list) -> list:
        out = []
        for study in studies:
            ledger = self.ledger(study)
            for rec in list(ledger.runs().values()):
                if rec["state"] not in HOLDS_GPUS:
                    continue
                o = self._reconcile_one(ledger, rec)
                if o is not None:
                    out.append(o)
        return out

    def _reconcile_one(self, ledger: Ledger, rec: dict) -> Optional[Outcome]:
        study, run_id = rec["study"], rec["run_id"]
        run_dir = Path(rec["run_dir"])
        if (run_dir / "exit_code").exists():
            return self._collect(ledger, rec)
        alive = self.session_alive(rec["node"], rec["tmux_session"])
        if alive is None:
            return None
        if alive:
            if rec["state"] == "launching":
                ledger.transition(run_id, "running", started_at=_read_float(run_dir / "started_at") or self.clock())
                return Outcome(study, run_id, "running", "session found on node")
            return None
        if (run_dir / "exit_code").exists():  # finished between the two checks
            return self._collect(ledger, rec)
        if rec["state"] == "launching":
            if self.clock() - rec["updated_at"] < LAUNCH_GRACE_S:
                return None
            ledger.transition(run_id, "queued", notes="launch never started a session; requeued")
            return Outcome(study, run_id, "requeued", "launch never started a session")
        ledger.transition(
            run_id,
            "crash",
            lost=True,
            ended_at=self.clock(),
            notes="lost: tmux session ended without writing exit_code (node reboot or killed)",
        )
        return Outcome(study, run_id, "lost", "session gone without exit_code")

    def _collect(self, ledger: Ledger, rec: dict) -> Outcome:
        study, run_id = rec["study"], rec["run_id"]
        run_dir = Path(rec["run_dir"])
        exit_path = run_dir / "exit_code"
        started = _read_float(run_dir / "started_at") or rec.get("started_at")
        ended = exit_path.stat().st_mtime
        fields = {"started_at": started, "ended_at": ended}
        try:
            rc = int(exit_path.read_text().strip())
        except ValueError:
            ledger.transition(run_id, "crash", notes="unreadable exit_code", **fields)
            return Outcome(study, run_id, "crashed", "unreadable exit_code")
        fields["exit_code"] = rc
        wandb = run_dir / "wandb_run"
        if wandb.exists():
            fields["wandb_run"] = wandb.read_text().strip()

        if rc != 0:
            if rc == 124:
                note = f"timed out after {rec['timeout_s'] / 3600:g}h"
            else:
                note = f"exit {rc}"
            tail = _log_tail(run_dir)
            ledger.transition(run_id, "crash", notes=f"{note}: {tail}" if tail else note, **fields)
            return Outcome(study, run_id, "crashed", note)

        m = rec["metric"]
        try:
            value = read_metric(run_dir, Metric(m["name"], m["direction"], m["source"]))
        except MetricError as e:
            ledger.transition(run_id, "crash", notes=f"exit 0 but {e}", **fields)
            return Outcome(study, run_id, "crashed", f"exit 0 but {e}")
        fields["metric"] = value

        if rec.get("eval_data"):
            try:
                current = hash_paths(self.project.root, rec["eval_data"], self.hash_cache)
            except MetricError as e:
                current = f"error: {e}"
            if current != rec.get("eval_data_sha256"):
                ledger.transition(run_id, "invalid", notes="eval data changed since approval", **fields)
                return Outcome(study, run_id, "invalid", "eval data changed since approval")
        ledger.transition(run_id, "done", **fields)
        return Outcome(study, run_id, "done", f"{m['name']}={value:g}")

    # ------------------------------------------------------------ cancelling

    def cancel(self, ledger: Ledger, run_id: str, reason: str = "cancelled by user") -> Outcome:
        rec = ledger.get(run_id)
        if rec is None:
            raise KeyError(run_id)
        study = rec["study"]
        if rec["state"] == "queued":
            ledger.transition(run_id, "cancelled", notes=reason)
            return Outcome(study, run_id, "cancelled", "was queued")
        if rec["state"] not in HOLDS_GPUS:
            return Outcome(study, run_id, "skipped", f"already {rec['state']}")
        session = rec.get("tmux_session") or ""
        if not session.startswith("rr-"):
            raise ValueError(f"refusing to kill non-rr session {session!r}")
        with file_lock(self.lock_path):
            res = self.runner.run(rec["node"], f"tmux kill-session -t {shlex.quote('=' + session)} 2>&1")
            gone = res.returncode == 0 or self.session_alive(rec["node"], session) is False
            if not gone:
                raise NodeError(f"could not kill {session} on {rec['node']}: {res.stdout.strip()}")
            ledger.transition(run_id, "cancelled", notes=reason, ended_at=self.clock())
        return Outcome(study, run_id, "cancelled", f"killed {session} on {rec['node']}")
